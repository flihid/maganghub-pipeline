import assert from 'node:assert/strict';
import './core.js';
const C=globalThis.MagangHubCore;
const config=structuredClone(C.defaults);
const jobs=C.jobs(config);
assert.equal(jobs.length,117);
assert.equal(new Set(jobs.map(j=>j.id)).size,117);
assert.deepEqual(jobs.slice(0,3).map(j=>j.fase),config.phases.map(p=>p.name));
assert.equal(jobs[0].since,'2026-08-31');
assert.equal(jobs[1].since,'2026-09-20');
assert.equal(jobs[2].since,'2026-10-25');
for(const job of jobs)assert.equal(Date.parse(job.until)-Date.parse(job.since),86400000);
assert.equal(C.wibDate('2026-09-20T17:30:00Z'),'2026-09-21');
assert.equal(C.wibDate('2026-09-20T17:30:00'),null);
assert.equal(C.phaseOf(config,'2026-09-20T17:30:00Z'),'fase3_penempatan');
assert.equal(C.inJob({since:'2026-09-20',until:'2026-09-21'},'2026-09-20T17:30:00Z'),false);
assert.equal(C.metric('1,234 Likes. Like'),1234);
assert.equal(C.metric('1.2K Likes. Like'),1200);
assert.equal(C.metric('0 Replies. Reply'),0);
assert.equal(C.metric('Likes. Like'),null);
assert.throws(()=>C.validate({...config,scrollDelayMs:1}));
assert.throws(()=>C.validate({...config,phases:[{name:'../bad',since:'2026-09-01',until:'2026-09-02'}]}));
assert.throws(()=>C.validate({...config,phases:[{name:'fase1_test',since:'2026-02-30',until:'2026-03-05'}]}));
console.log('PASS: 117 daily jobs, interleaving, WIB boundaries, metrics, configuration validation');
